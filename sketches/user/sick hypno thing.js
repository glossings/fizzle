bg('#04040a')
ambient(0.3)
point({ color: '#88aaff', intensity: 60 }).pos(4, 3, 3).out()
point({ color: '#ffaa66', intensity: 40 }).pos(-3, -2, 4).out()

icosa({ radius: 2, detail: 12 })
  .noise({ amp: 1.5, freq: 0.4, octaves: 4, speed: 0.1 })
  .rotate(0, t => t * 0.1, 0)
  // .material({ color: '#223355', roughness: 0.4, metalness: 0.3 })
  .out()

scene()
  // .tile(4, 4, (s, i) => s.hue(i % 7 / 7))
  .comp(input("fbend"), "difference", 0.7)
  .scale(0.7)
  .scale(t => Math.abs(Math.sin(t * 0.5)) * 2 + 0.5)
  .rotate(0.1)
  .bloom({ threshold: 0.55 })
  .out("fbend").rotate(t => t * 0.1)
  .comp(s => s.edge(), "screen")
  .comp(s => s.slope(), "difference")
  .remap(ramp({ type: "radial" }))
  .out()
